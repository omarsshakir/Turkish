/**
 * Verb patterns, as an overlay.
 *
 * The content report asks a question no vocabulary file answers: *does this
 * verb tell a student how to use it?* Phase 7 found that **127 verbs carried
 * no note, no collocation and no sense** — and that the 32 worst offenders
 * were the 32 commonest verbs in Turkish. `olmak`, `yapmak`, `gitmek`,
 * `gelmek`, `görmek`, `bilmek` were added earliest and explained least.
 *
 * A translation is not enough for a Turkish verb. `bakmak` is "to look", and a
 * student who knows only that will write `beni bakıyor` — because nothing told
 * them it takes the dative. The information that makes a verb *usable* is:
 *
 *   - which case its object takes
 *   - whether it is transitive
 *   - which verb it pairs with (`girmek`/`çıkmak`, `yanmak`/`yakmak`)
 *   - the mistake a speaker of Arabic or Kurdish reliably makes
 *
 * ---------------------------------------------------------------------------
 * Why an overlay rather than editing the vocabulary files
 * ---------------------------------------------------------------------------
 *
 * The 127 verbs live across nineteen files. Case government is a *system*, and
 * a system is reviewable only when you can see it in one place: it is by
 * reading `bakmak -e`, `girmek -e`, `binmek -e`, `başlamak -e` together that
 * the pattern behind them becomes visible, and by reading `çıkmak -den`,
 * `korkmak -den`, `nefret etmek -den`, `bahsetmek -den` together that the
 * second pattern does.
 *
 * This is the fifth overlay, applied in `content/index.ts` beside connections,
 * collocations, origins and senses, under the same two rules: a hand-written
 * note in a vocabulary file always wins, and an ambiguous word (a homonym) is
 * never decorated.
 */

