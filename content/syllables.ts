/**
 * The syllable and pronunciation database.
 *
 * Turkish is unusually regular: syllables are almost always CV or CVC, stress
 * falls on the last syllable unless something specific moves it, and vowel
 * harmony means the vowels in a word are predictable once you know the first
 * one. A student who internalises that can pronounce a word they have never
 * seen — which is the point of this section.
 *
 * The sections aimed at Arabic and Kurdish speakers are not generic. They
 * target the specific contrasts those two languages do not make, because a
 * sound you cannot hear is a sound you cannot produce:
 *
 *   - Arabic has no /o/ vs /ö/ or /u/ vs /ü/ distinction, and no /p/ vs /b/
 *     contrast in many dialects.
 *   - Sorani has ö and ü sounds closer to Turkish, but no ı, and the Turkish
 *     ğ has no Kurdish equivalent at all.
 *
 * Every entry carries Turkish, its syllable break, a stress-marked
 * pronunciation, and both translations, so it plugs straight into the
 * existing audio component.
 */

