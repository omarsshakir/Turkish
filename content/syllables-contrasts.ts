/**
 * Minimal pairs, and the sounds each first language gets wrong.
 *
 * The earlier sound sections are *inventories* — here is every vowel, here is
 * every consonant. These are **diagnostics**: pairs of real Turkish words that
 * differ in exactly one sound, so a student can find out whether they are
 * actually hearing the difference or only believing they are.
 *
 * Three of the sections are language-specific, because Arabic and Sorani
 * speakers fail on different things:
 *
 *   Arabic ear   ı/i, o/ö, u/ü (five vowels it does not have); p/b, v/w;
 *                and above all **ğ is not غ**.
 *   Sorani ear   the vowel system is closer, so the problem moves to the
 *                consonants: ç/c, ş/j, and final-consonant devoicing.
 *
 * Every word here is real curriculum vocabulary. Nothing was invented to make
 * a pair work — where no genuine minimal pair exists, the section uses a
 * near-pair and says so.
 */

